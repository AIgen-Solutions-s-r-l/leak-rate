"""Tables and a markdown summary for the frontier-model experiments (results/frontier/*.json, results/eval/llm_self-*).

Writes paper/tables_frontier.tex and results/frontier_summary.md. Tolerates missing runs (lanes still in progress).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
FR = ROOT / "results" / "frontier"
EV = ROOT / "results" / "eval"
TEX = ROOT / "paper" / "tables_frontier.tex"
MD = ROOT / "results" / "frontier_summary.md"

CONSUMER_RUNS = [  # (file stem, label)
    ("downstream__opus-5-5__medium", "Opus 5.5, medium"),
    ("downstream__opus-5-5__low", "Opus 5.5, low"),
    ("downstream__opus-5-5__high", "Opus 5.5, high"),
    ("downstream__sonnet-5-5__medium", "Sonnet 5.5, medium"),
    ("downstream__haiku-5-5__medium", "Haiku 5.5, medium"),
]
COND_LABEL = {"typed": r"typed (\textsc{d+o+l})", "opaque": r"opaque (\textsc{d+o+l})", "direct_only": r"typed (\textsc{direct\_only})",
              "all": r"typed (\textsc{all})", "oracle": r"oracle typed (\textsc{d+o+l})"}
COND_ORDER = ["typed", "opaque", "direct_only", "all", "oracle"]
ATTACK_CONDS = [("raw", "raw text (ceiling)"), ("typed", "typed d+o+l"), ("opaque", "opaque d+o+l"), ("direct_only", "typed direct\\_only"),
                ("all", "typed all"), ("oracle", "oracle typed d+o+l")]
ATTRS = ["gender", "age", "city", "profession", "employer", "nationality", "marital_status", "diagnosis"]


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pp(x, d=1):
    return f"{100 * x:.{d}f}"


def delta(dv):
    if not dv:
        return "--"
    return f"{100 * dv['diff']:+.1f} [{100 * dv['lo']:+.1f}, {100 * dv['hi']:+.1f}]"


def ci(x, d=1):
    if not x:
        return "--"
    return f"{pp(x['rate'], d)} [{pp(x['lo'], d)}, {pp(x['hi'], d)}]"


def _fit(lines):
    """Shrink every tabular to the text width (adjustbox only scales down, never up)."""
    out = []
    for ln in lines:
        if ln.lstrip().startswith(r"\begin{tabular}"):
            out.append(r"\begin{adjustbox}{max width=\textwidth}")
        # close the box right after the tabular, even when \end{table} follows on the same line
        out.append(ln.replace(r"\end{tabular}", r"\end{tabular}\end{adjustbox}") if r"\end{tabular}" in ln else ln)
    return out


def main():
    tex, md = [], ["# Frontier-model experiments (test split, 400 documents)", ""]
    tex.append("% auto-generated by scripts/make_frontier_tables.py — do not edit by hand")

    # ------------------------------------------------------------- Table F1: downstream quality per consumer model and condition
    rows = []
    for stem, lab in CONSUMER_RUNS:
        d = load(FR / f"{stem}.json")
        if not d:
            continue
        raw = {t: np.mean(list(d["quality"]["scores"][t]["raw"].values())) for t in ("qa", "classify", "extract") if t in d["quality"]["scores"]}
        rows.append((lab, "raw", d["n_docs"], raw, None, None, None, d))
        for cond in COND_ORDER:
            if cond not in d["conditions"]:
                continue
            dv = {t: d["deltas_vs_raw"].get(f"{t}:{cond}") for t in ("qa", "classify", "extract")}
            jw = (d.get("judge_vs_raw") or {}).get(cond)
            ag = (d.get("agreement") or {}).get(cond) or {}
            rows.append((lab, cond, d["n_docs"], None, dv, jw, ag, d))
    if rows:
        tex.append(r"\begin{table*}[t]\centering\small")
        tex.append(r"\caption{Downstream quality on the test split. Raw rows give absolute accuracy (\%); pseudonymized rows give $\Delta$ = quality(condition) $-$ quality(raw) in points with 95\,\% paired-bootstrap CIs over documents (pre-registered non-inferiority margin: 2 points). The pairwise summary judge is reported in the text only (\S\ref{sec:results}), since its preference is an artifact of identifier completeness. Agr.\ = heuristic agreement-error rate on the pseudonymized summaries (\S\ref{sec:downstream}). Pseudonymizer: Presidio + regex unless \textsc{oracle}.}")
        tex.append(r"\label{tab:downstream}")
        tex.append(r"\begin{tabular}{llrrrrr}\toprule")
        tex.append(r"Consumer & condition & $N$ & QA & classify & extract & agr.\ err.\ \% \\ \midrule")
        md += ["## Downstream quality (Δ vs raw, points, 95% paired-bootstrap CI)", "",
               "| consumer | condition | N | QA | classify | extract | agreement err % |", "|---|---|---|---|---|---|---|"]
        last = None
        for lab, cond, n, raw, dv, jw, ag, d in rows:
            first = lab if lab != last else ""
            if lab != last and last is not None:
                tex.append(r"\midrule")
            last = lab
            if cond == "raw":
                cells = [pp(raw.get("qa", 0)), pp(raw.get("classify", 0)), pp(raw.get("extract", 0)), "--"]
                tex.append(f"{first} & raw & {n} & " + " & ".join(cells) + r" \\")
                md.append(f"| {lab} | raw (absolute %) | {n} | " + " | ".join(cells) + " |")
            else:
                jws = f"{jw['win_rate_vs_raw']:.2f} [{jw['lo']:.2f}, {jw['hi']:.2f}]" if jw else "--"
                ags = ci(ag.get("rate")) if ag else "--"
                cells = [delta(dv["qa"]), delta(dv["classify"]), delta(dv["extract"]), ags]
                tex.append(f"{first} & {COND_LABEL.get(cond, cond)} & {n} & " + " & ".join(cells) + r" \\")
                md.append(f"| {lab} | {cond} | {n} | " + " | ".join(cells) + " |")
        tex.append(r"\bottomrule\end{tabular}\end{table*}")
        tex.append("")
        md.append("")

    # ------------------------------------------------------------- Table F2: variance across repeat runs + cross-judge
    reps = [("downstream__opus-5-5__medium", "primary, 400"), ("downstream__opus-5-5__medium__rep3", "rep3, 400"),
            ("downstream__opus-5-5__medium__rep1", "rep1, 100"), ("downstream__opus-5-5__medium__rep2", "rep2, 100")]
    rrows = [(lab, load(FR / f"{stem}.json")) for stem, lab in reps]
    rrows = [(lab, d) for lab, d in rrows if d]
    xj = load(FR / "downstream__opus-5-5__medium__opusjudge.json")
    if len(rrows) > 1 or xj:
        md += ["## Run-to-run variance of Δ(typed) (Opus 5.5 medium) and cross-judge", "", "| run | N | QA Δ | classify Δ | extract Δ |", "|---|---|---|---|---|"]
        tex.append(r"\begin{table}[t]\centering\small")
        tex.append(r"\caption{Run-to-run variance of $\Delta$(typed) for the Opus 5.5 consumer: the primary run and repeat runs with a fresh cache salt (points, 95\,\% CI). The spread across runs is the sampling noise of the model itself and should be read next to the bootstrap CI, which only captures document sampling.}")
        tex.append(r"\label{tab:variance}")
        tex.append(r"\begin{tabular}{lrrrr}\toprule Run & $N$ & QA & classify & extract \\ \midrule")
        for lab, d in rrows:
            cells = [delta(d["deltas_vs_raw"].get(f"{t}:typed")) for t in ("qa", "classify", "extract")]
            tex.append(f"{lab} & {d['n_docs']} & " + " & ".join(cells) + r" \\")
            md.append(f"| {lab} | {d['n_docs']} | " + " | ".join(cells) + " |")
        tex.append(r"\bottomrule\end{tabular}\end{table}")
        tex.append("")
        if xj:
            md.append("")
            for cond in ("typed", "opaque"):
                j = (xj.get("judge_vs_raw") or {}).get(cond)
                if j:
                    md.append(f"- Opus-as-judge win rate vs raw, {cond}: {j['win_rate_vs_raw']:.2f} [{j['lo']:.2f}, {j['hi']:.2f}] (n={j['n']})")
        md.append("")

    # ------------------------------------------------------------- Table F2b: summary judge, prompt x judge model
    jrows = [("Sonnet 5.5", "default", load(FR / "downstream__opus-5-5__medium.json")),
             ("Opus 5.5", "default", load(FR / "downstream__opus-5-5__medium__opusjudge.json")),
             ("Qwen2.5-72B", "default", load(FR / "judge_default__qwen2.5-72b__opus-medium.json")),
             ("Qwen2.5-72B", "completeness-blind", load(FR / "judge_blind__qwen2.5-72b__opus-medium.json"))]
    jrows = [(m, p, d) for m, p, d in jrows if d and d.get("judge_vs_raw")]
    if jrows:
        md += ["## Pairwise summary judge on the Opus 5.5 consumer run: win rate of the pseudonymized summary vs raw (0.5 = parity)", "",
               "| judge | prompt | typed | opaque | oracle |", "|---|---|---|---|---|"]
        tex.append(r"\begin{table}[t]\centering\small")
        tex.append(r"\caption{Pairwise summary judge on the Opus~5.5 consumer run: share of documents in which the judge prefers the reverse-mapped pseudonymized summary over the raw-input summary (ties count one half, both presentation orders, 95\,\% bootstrap CI over documents; 0.5 = parity). The default prompt rewards identifier completeness (\S\ref{sec:results}); the completeness-blind prompt tells the judge to ignore how many names, codes and addresses a summary carries.}")
        tex.append(r"\label{tab:judge}")
        tex.append(r"\begin{tabular}{llrrr}\toprule Judge & Prompt & typed & opaque & \textsc{oracle} \\ \midrule")
        for m, p, d in jrows:
            cells = []
            for cond in ("typed", "opaque", "oracle"):
                j = d["judge_vs_raw"].get(cond)
                cells.append(f"{j['win_rate_vs_raw']:.2f} [{j['lo']:.2f}, {j['hi']:.2f}]" if j else "--")
            tex.append(f"{m} & {p} & " + " & ".join(cells) + r" \\")
            md.append(f"| {m} | {p} | " + " | ".join(cells) + " |")
        tex.append(r"\bottomrule\end{tabular}\end{table}")
        tex.append("")
        md.append("")

    # ------------------------------------------------------------- Table F3: LLM-judged agreement
    aj = sorted(FR.glob("agreement_judge__*.json"))
    if aj:
        md += ["## LLM-judged grammatical agreement (error rate among pseudonyms with gendered agreement)", "",
               "| consumer run | condition | pseudonyms | with gendered agreement (%) | inconsistent | error rate % [CI] |", "|---|---|---|---|---|---|"]
        tex.append(r"\begin{table}[t]\centering\small")
        tex.append(r"\caption{LLM-judged agreement (Sonnet 5.5 judge, \S\ref{sec:downstream}). ``Gendered'' = share of person pseudonyms in the summary for which the model produced any gender-marked agreement; error = share of those whose agreement contradicts the gold gender. Cluster-bootstrap CIs over documents.}")
        tex.append(r"\label{tab:agreement-judge}")
        tex.append(r"\begin{tabular}{llrrrr}\toprule Consumer run & condition & pseudonyms & gendered \% & inconsistent & error \% [CI] \\ \midrule")
        for f in aj:
            d = load(f)
            run = f.stem.replace("agreement_judge__", "").replace("__", ", ")
            for cond, v in d["by_condition"].items():
                if not v.get("error_rate"):
                    continue
                share = pp(v["share_with_agreement"], 0) if v.get("share_with_agreement") is not None else "--"
                tex.append(f"{run} & {cond} & {v.get('pseudonyms_total', '--')} & {share} & {v['pseudonyms_inconsistent']} & {ci(v['error_rate'])} \\\\")
                md.append(f"| {run} | {cond} | {v.get('pseudonyms_total', '--')} | {share} | {v['pseudonyms_inconsistent']} | {ci(v['error_rate'])} |")
        tex.append(r"\bottomrule\end{tabular}\end{table}")
        tex.append("")
        md.append("")

    # ------------------------------------------------------------- Table F4: llm_self leak rates vs local systems
    evals = {}
    for f in EV.glob("*.eval.json"):
        d = load(f)
        L = d["leak"]
        if L["mode"] == "typed" and L["policy"] == "direct+org+loc":
            evals[L["system"]] = d
    order = ["presidio", "presidio+regex", "presidio+casenorm+regex", "wikineural+regex", "wikineural+casenorm+regex", "gliner+regex", "finetuned+regex", "finetuned-xt+regex"] + sorted(s for s in evals if s.startswith("llm_self")) + ["oracle"]
    order = [s for s in order if s in evals]
    if any(s.startswith("llm_self") for s in order):
        md += ["## Frontier model as its own anonymizer (llm_self) vs local systems — typed, direct+org+loc", "",
               "| system | N | doc leak % [CI] | incl. partial | PER mention leak | over-redaction /1k | k̂<11 share |", "|---|---|---|---|---|---|---|"]
        tex.append(r"\begin{table*}[t]\centering\small")
        tex.append(r"\caption{The frontier model as its own anonymizer (\texttt{llm\_self}, one call per document asking for all identifier mentions) against the local systems, same policy and metrics as Table~\ref{tab:headline}. Not a deployable option (the provider sees the raw text): it bounds what a local detector forgoes.}")
        tex.append(r"\label{tab:llmself}")
        tex.append(r"\begin{tabular}{lrrrrrr}\toprule System & $N$ & doc.\ leak \% & incl.\ partial & \texttt{PER} leak & over-red.\ & $\hat k<11$ \\ \midrule")
        for s in order:
            L, K = evals[s]["leak"], evals[s]["kanon"]
            per = L["per_category"].get("PER", {}).get("strict")
            cells = [str(L["n_docs"]), ci(L["doc_leak_rate"]), ci(L["doc_leak_rate_partial"]), ci(per), f"{L['over_redaction_per_1k_tokens']:.1f}",
                     f"{100 * K['pop_k_lt11_share']:.0f}\\,\\%"]
            tex.append(f"\\texttt{{{s.replace('_', chr(92) + '_')}}} & " + " & ".join(cells) + r" \\")
            md.append(f"| {s} | " + " | ".join(c.replace('\\,\\%', '%') for c in cells) + " |")
        tex.append(r"\bottomrule\end{tabular}\end{table*}")
        tex.append("")
        md.append("")

    # ------------------------------------------------------------- Table F5: attacker
    att = {c: load(FR / f"attack__opus-5-5__{c}.json") for c, _ in ATTACK_CONDS}
    att_s = load(FR / "attack__sonnet-5-5__typed.json")
    extra = [("qwen14_typed", "typed d+o+l, Qwen2.5-14B attacker (local)", load(FR / "attack__qwen2.5-14b__typed.json")),
             ("qwen14_raw", "raw text, Qwen2.5-14B attacker (100 docs)", load(FR / "attack__qwen2.5-14b__raw.json")),
             ("qwen14_oracle", "oracle, Qwen2.5-14B attacker (100 docs)", load(FR / "attack__qwen2.5-14b__oracle.json")),
             ("q72_typed", "typed d+o+l, Qwen2.5-72B attacker (RunPod)", load(FR / "attack__qwen2.5-72b__typed.json")),
             ("q72_opaque", "opaque d+o+l, Qwen2.5-72B attacker", load(FR / "attack__qwen2.5-72b__opaque.json")),
             ("q72_donly", "typed direct\\_only, Qwen2.5-72B attacker", load(FR / "attack__qwen2.5-72b__direct_only.json")),
             ("q72_raw", "raw text, Qwen2.5-72B attacker", load(FR / "attack__qwen2.5-72b__raw.json")),
             ("q72_oracle", "oracle, Qwen2.5-72B attacker", load(FR / "attack__qwen2.5-72b__oracle.json"))]
    if any(att.values()):
        md += ["## LLM attacker (Opus 5.5): attribute recall % on the data subject, surname recovery, inference-based k̂", "",
               "| condition | " + " | ".join(ATTRS) + " | surname | k̂ median | k̂<11 | k̂<100 |", "|---|" + "---|" * (len(ATTRS) + 4)]
        tex.append(r"\begin{table*}[t]\centering\small")
        tex.append(r"\caption{LLM attacker (Opus~5.5 unless stated, \S\ref{sec:attacker}): recall (\%) of the data subject's attributes inferred from the text the consumer model receives, surname recovery, and the population $\hat k$ recomputed on the correctly inferred attributes (same marginals as Table~\ref{tab:kanon}). Raw text is the ceiling; \textsc{oracle} isolates what the text reveals once every gold span is replaced.}")
        tex.append(r"\label{tab:attacker}")
        tex.append(r"\begin{tabular}{l" + "r" * len(ATTRS) + r"rrrr}\toprule")
        tex.append("Condition & " + " & ".join(a.replace("_", " ") for a in ATTRS) + r" & surname & med.\ $\hat k$ & $\hat k<11$ & $\hat k<100$ \\ \midrule")
        for c, lab in ATTACK_CONDS + [("sonnet", "typed d+o+l, Sonnet attacker")] + [(k, lab) for k, lab, dd in extra if dd]:
            d = att_s if c == "sonnet" else (att.get(c) if c in att else next((dd for k, _, dd in extra if k == c), None))
            if not d:
                continue
            rec = [pp(d["attr_recovery"][a]["rate"], 0) if d["attr_recovery"].get(a) else "--" for a in ATTRS]
            sur = pp(d["surname_recovery"]["rate"], 1) if d.get("surname_recovery") else "--"
            cells = rec + [sur, f"{d['pop_k_median']:,.0f}", f"{100 * d['pop_k_lt11_share']:.0f}\\,\\%", f"{100 * d['pop_k_lt100_share']:.0f}\\,\\%"]
            tex.append(f"{lab} & " + " & ".join(cells) + r" \\")
            md.append(f"| {lab} | " + " | ".join(x.replace('\\,\\%', '%') for x in cells) + " |")
        tex.append(r"\bottomrule\end{tabular}\end{table*}")
        tex.append("")
        md.append("")
        # surface survival vs inference, for the typed condition
        ev = evals.get("presidio+regex")
        if ev and att.get("typed"):
            # surface survival among *applicable* documents (same denominator as attacker recall)
            import json as _json
            prof = {}
            for line in (ROOT / "data" / "benchmark.jsonl").read_text(encoding="utf-8").splitlines():
                if line.strip():
                    d0 = _json.loads(line)
                    prof[d0["doc_id"]] = d0["quasi_profile"]
            key = {"gender": "gender", "age": "age", "city": "city", "profession": "profession", "employer": "employer",
                   "nationality": "nationality", "marital_status": "marital_status", "diagnosis": "diagnosis"}
            surv_app = {}
            for a in ATTRS:
                rows_a = [r["surviving_quasi"].get(a, False) for r in ev["per_document"] if prof.get(r["doc_id"], {}).get(key[a]) not in (None, "")]
                surv_app[a] = (sum(bool(x) for x in rows_a) / len(rows_a)) if rows_a else None
            md += ["### Surface survival vs attacker recall (typed d+o+l, Presidio + regex; both among documents where the attribute applies)", "",
                   "| attribute | surface survival % | attacker recall % | attacker precision % |", "|---|---|---|---|"]
            tex.append(r"\begin{table}[t]\centering\small")
            tex.append(r"\caption{Readable versus inferable (typed, \textsc{direct+org+loc}, Presidio + regex): share of data subjects whose attribute is still readable verbatim in $d'$ against the share the Opus~5.5 attacker infers correctly, both among documents where the attribute applies.}")
            tex.append(r"\label{tab:readable-inferable}")
            tex.append(r"\begin{tabular}{lrrr}\toprule Attribute & readable \% & inferred \% & precision \% \\ \midrule")
            for a in ATTRS:
                sv = surv_app.get(a)
                r = att["typed"]["attr_recovery"].get(a)
                pr = att["typed"]["attr_precision"].get(a)
                md.append(f"| {a} | {pp(sv, 0) if sv is not None else '--'} | {pp(r['rate'], 0) if r else '--'} | {pp(pr, 0) if pr is not None else '--'} |")
                tex.append(f"{a.replace('_', ' ')} & {pp(sv, 0) if sv is not None else '--'} & {pp(r['rate'], 0) if r else '--'} & {pp(pr, 0) if pr is not None else '--'} \\\\")
            tex.append(r"\bottomrule\end{tabular}\end{table}")
            tex.append("")
            md.append("")

    # ------------------------------------------------------------- spend
    try:
        sys.path.insert(0, str(ROOT / "scripts"))
        import io, contextlib
        import cost  # noqa
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            cost.main()
        md += ["## Spend (list prices, from the call cache)", "", "```", buf.getvalue().rstrip(), "```", ""]
    except Exception as e:  # pragma: no cover
        md.append(f"(cost summary unavailable: {e})")

    TEX.write_text("\n".join(_fit(tex)) + "\n", encoding="utf-8")
    MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {TEX} ({len(tex)} lines) and {MD} ({len(md)} lines)")


if __name__ == "__main__":
    main()
