"""Generate paper/tables.tex from results/eval/*.eval.json (run after `leakrate report`)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVAL = ROOT / "results" / "eval"
OUT = ROOT / "paper" / "tables.tex"

ORDER = ["identity", "regex", "presidio", "presidio+regex", "presidio+casenorm+regex", "gliner", "gliner+regex", "wikineural+regex", "wikineural+casenorm+regex", "finetuned+regex", "finetuned-xt+regex", "oracle"]
LABEL = {"identity": "identity (no replacement)", "regex": "regex baseline", "presidio": "Presidio",
         "presidio+regex": "Presidio + regex", "gliner": "GLiNER", "gliner+regex": "GLiNER + regex", "finetuned": "fine-tuned encoder", "finetuned+regex": "fine-tuned + regex (in-distribution)", "finetuned-xt+regex": "fine-tuned + regex (cross-template)", "presidio+casenorm+regex": "Presidio + case norm.\\ + regex", "wikineural+regex": "WikiNEuRal + regex", "wikineural+casenorm+regex": "WikiNEuRal + case norm.\\ + regex", "oracle": "oracle (gold spans)"}
DIRECT = ["PER", "ADDRESS", "DATE_BIRTH", "CF", "IBAN", "PIVA", "EMAIL", "PHONE", "DOC_ID", "PLATE"]
QUASI = ["ORG", "LOC", "DATE", "AGE", "PROFESSION", "HEALTH"]
FORMS = [("full", "Name Surname"), ("inverted", "SURNAME Name"), ("upper", "ALL CAPS"), ("surname", "surname only"),
         ("first", "first name only"), ("initial", "N. Surname")]


def ci(x, digits=1):
    if x is None or x.get("n", 0) == 0:
        return "--"
    return f"{100 * x['rate']:.{digits}f} [{100 * x['lo']:.{digits}f}, {100 * x['hi']:.{digits}f}]"


def load():
    rows = {}
    for f in EVAL.glob("*.eval.json"):
        d = json.loads(f.read_text(encoding="utf-8"))
        L = d["leak"]
        rows[(L["system"], L["mode"], L["policy"])] = d
    return rows


def _fit(lines):
    """Shrink every tabular to the text width (adjustbox only scales down, never up)."""
    out = []
    for ln in lines:
        if ln.lstrip().startswith(r"\begin{tabular}"):
            out.append(r"\begin{adjustbox}{max width=\textwidth}")
        # close the box right after the tabular, even when \end{table} follows on the same line
        out.append(ln.replace(r"\end{tabular}", r"\end{tabular}\end{adjustbox}") if r"\end{tabular}" in ln else ln)
    return out


def main():
    rows = load()
    if not rows:
        sys.exit("no eval files")
    out = []
    # ---------------------------------------------------------------- Table 1: headline
    out.append("% auto-generated by scripts/make_tables.py — do not edit by hand")
    out.append(r"\begin{table*}[t]\centering\small")
    out.append(r"\caption{Leak rate on the test split ($N=400$ documents, 100 per domain), typed pseudonyms, replacement policy \textsc{direct+org+loc} unless stated. Document leak rate = share of documents in which at least one direct identifier survives verbatim; ``incl.\ partial'' also counts discriminating fragments (\S\ref{sec:leak}). 95\,\% cluster-bootstrap CIs over documents ($B=2000$). Over-redaction = replaced spans outside any gold span, per 1\,000 tokens. $\hat k$ = estimated population equivalence-class size of the surviving quasi-identifier tuple (\S\ref{sec:kanon}).}")
    out.append(r"\label{tab:headline}")
    out.append(r"\begin{tabular}{llrrrrrrr}\toprule")
    out.append(r"System & policy & doc.\ leak \% & incl.\ partial \% & direct-mention leak \% & over-red.\ & median $\hat k$ & $\hat k<11$ & $\hat k<100$ \\ \midrule")
    keys = [(s, "typed", "direct+org+loc") for s in ORDER] + [("presidio+regex", "typed", "direct_only"), ("presidio+casenorm+regex", "typed", "direct_only"), ("presidio+regex", "typed", "all")]
    for k in keys:
        if k not in rows:
            continue
        L, K = rows[k]["leak"], rows[k]["kanon"]
        pol = k[2].replace("_", r"\_").replace("+", "+")
        out.append(f"{LABEL[k[0]]} & \\textsc{{{pol}}} & {ci(L['doc_leak_rate'])} & {ci(L['doc_leak_rate_partial'])} & {ci(L['direct_mention_leak'])} & "
                   f"{L['over_redaction_per_1k_tokens']:.1f} & {K['pop_k_median']:,.0f} & {100 * K['pop_k_lt11_share']:.0f}\\,\\% & {100 * K['pop_k_lt100_share']:.0f}\\,\\% \\\\")
    out.append(r"\bottomrule\end{tabular}\end{table*}")
    out.append("")
    # ---------------------------------------------------------------- Table 2: per category
    sysk = [("presidio+regex", "typed", "direct+org+loc"), ("presidio+casenorm+regex", "typed", "direct+org+loc"), ("wikineural+casenorm+regex", "typed", "direct+org+loc"), ("gliner+regex", "typed", "direct+org+loc"), ("finetuned-xt+regex", "typed", "direct+org+loc")]
    sysk = [k for k in sysk if k in rows]
    out.append(r"\begin{table*}[t]\centering\small")
    out.append(r"\caption{Strict leak rate per category, \% [95\,\% CI], typed pseudonyms, policy \textsc{direct+org+loc}. Quasi-identifiers (lower block) are replaced only when the policy includes them (here \pseud{ORG} and \pseud{LOC}); the regex baseline is at 100\,\% on every unstructured category and 0\,\% on every structured one. Mentions column: ground-truth mentions in the test split.}")
    out.append(r"\label{tab:percat}")
    out.append(r"\begin{tabular}{llr" + "r" * len(sysk) + r"}\toprule")
    out.append("Category & kind & mentions & " + " & ".join(LABEL[k[0]] for k in sysk) + r" \\ \midrule")
    first = rows[sysk[0]]["leak"]["per_category"]
    for c in DIRECT + [None] + QUASI:
        if c is None:
            out.append(r"\midrule")
            continue
        if c not in first:
            continue
        kind = first[c]["kind"]
        out.append(f"\\texttt{{{c.replace('_', chr(92) + '_')}}} & {kind} & {first[c]['strict']['n']} & " +
                   " & ".join(ci(rows[k]["leak"]["per_category"].get(c, {}).get("strict")) for k in sysk) + r" \\")
    out.append(r"\bottomrule\end{tabular}\end{table*}")
    out.append("")
    # ---------------------------------------------------------------- Table 3: PER by form + domain
    k = ("presidio+regex", "typed", "direct+org+loc")
    if k in rows:
        L = rows[k]["leak"]
        out.append(r"\begin{table}[t]\centering\small")
        out.append(r"\caption{Where the names leak (Presidio + regex, typed, \textsc{direct+org+loc}). Left: strict leak rate of \texttt{PER} mentions by surface form. Right: document leak rate by domain.}")
        out.append(r"\label{tab:forms}")
        out.append(r"\begin{tabular}{lrr}\toprule Surface form & $n$ & leak \% [CI] \\ \midrule")
        for f, lab in FORMS:
            if f in L["per_form"]:
                out.append(f"{lab} & {L['per_form'][f]['n']} & {ci(L['per_form'][f])} \\\\")
        out.append(r"\midrule Domain & $N$ & doc.\ leak \% [CI] \\ \midrule")
        for dom in ["legal", "financial", "hr", "clinical"]:
            if dom in L["by_domain"]:
                out.append(f"{dom} & {L['by_domain'][dom]['n']} & {ci(L['by_domain'][dom])} \\\\")
        out.append(r"\bottomrule\end{tabular}\end{table}")
        out.append("")
    # ---------------------------------------------------------------- Table 4: quasi survival + k
    out.append(r"\begin{table*}[t]\centering\small")
    out.append(r"\caption{Quasi-identifier survival (share of documents in which the attribute of the data subject is still readable in $d'$) and re-identification risk. Corpus $k$: equivalence-class size within the released test corpus; $\hat k$: population estimate under independence from reference marginals (optimistic). $l=1$: share of clinical documents whose equivalence class contains a single diagnosis.}")
    out.append(r"\label{tab:kanon}")
    attrs = ["gender", "age", "city", "profession", "employer", "nationality", "marital_status", "diagnosis"]
    out.append(r"\begin{tabular}{l" + "r" * len(attrs) + r"rrrrr}\toprule")
    out.append("System (policy) & " + " & ".join(a.replace("_", " ") for a in attrs) + r" & corpus $k{=}1$ & med.\ $\hat k$ & p10 $\hat k$ & $\hat k<11$ & $l{=}1$ \\ \midrule")
    for kk in keys:
        if kk not in rows:
            continue
        K = rows[kk]["kanon"]
        ld = K.get("l_diversity_clinical") or {}
        out.append(f"{LABEL[kk[0]]} ({kk[2].replace('_', '-')}) & " + " & ".join(f"{100 * K['attr_survival'].get(a, 0):.0f}" for a in attrs) +
                   f" & {100 * K['corpus_k_unique_share']:.0f}\\,\\% & {K['pop_k_median']:,.0f} & {K['pop_k_p10']:,.0f} & {100 * K['pop_k_lt11_share']:.0f}\\,\\% & {100 * ld.get('l1_share', 0):.0f}\\,\\% \\\\")
    out.append(r"\bottomrule\end{tabular}\end{table*}")
    OUT.write_text("\n".join(_fit(out)) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(out)} lines)")


if __name__ == "__main__":
    main()
